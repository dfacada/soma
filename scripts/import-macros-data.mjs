// Generates src/lib/food-data.ts from the Macros repo's own data files, so David's plans, recipes and snack presets
// come across exactly, with nothing retyped. Reads the sibling repo and writes only inside this one.
//
//   node scripts/import-macros-data.mjs [path-to-Macros]        (default: ../Macros)
//
// This copies *code constants* (what Macros ships with), not anyone's data: Macros and its Supabase project stay
// untouched, as CLAUDE.md requires. Re-run it if the Macros files change; never edit food-data.ts by hand.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const macros = path.resolve(process.argv[2] || path.join(import.meta.dirname, "..", "..", "Macros"));
const load = (file) => import(pathToFileURL(path.join(macros, "lib", "data", file)).href);
const [{ MEAL_PLANS, BOWL_VARIANTS }, { SNACK_PRESETS }, { RECIPES }] = await Promise.all([load("plans.ts"), load("snacks.ts"), load("recipes.ts")]);

// Macros names its meals by id; Soma has four fixed slots. Anything else a plan carries (the Standard plan's
// anytime whey) is an extra: it becomes a quick snack, because in Soma four meals close the day.
const SLOT = { shake: "breakfast", "bowl-noon": "lunch", yogurt: "snack", snack: "snack", "bowl-pm": "dinner" };
const meal = (m) => ({ name: m.name, kcal: m.kcal, protein: m.protein, carbs: m.carbs, fat: m.fat, time: m.time, desc: m.desc, ...(m.fixedPortion ? { fixedPortion: true } : {}) });

const plans = {};
for (const [id, p] of Object.entries(MEAL_PLANS)) {
  const meals = {}, extras = [];
  for (const m of p.meals) { const slot = SLOT[m.id]; if (slot && !meals[slot]) meals[slot] = meal(m); else extras.push(meal(m)); }
  for (const slot of ["breakfast", "lunch", "snack", "dinner"]) if (!meals[slot]) throw new Error(`${id} has no meal for ${slot}`);
  plans[id] = { id, name: p.name, badge: p.badge, desc: p.desc, targets: p.targets, meals, extras };
}

const snacks = SNACK_PRESETS.map((s) => ({ name: s.name, portion: s.portion, kcal: s.kcal, protein: s.protein, carbs: s.carbs, fat: s.fat }));
for (const p of Object.values(plans)) for (const x of p.extras) if (!snacks.some((s) => s.name === x.name)) snacks.push({ name: x.name, portion: "1 serving", kcal: x.kcal, protein: x.protein, carbs: x.carbs, fat: x.fat });

const recipes = Object.entries(RECIPES).flatMap(([group, list]) => list.map((r) => ({
  id: r.id, group, name: r.name, time: r.time || "", servings: r.servings, isMealPrep: Boolean(r.isMealPrep), ...(r.fixedPortion ? { fixedPortion: true } : {}),
  kcal: r.macros.kcal, protein: r.macros.protein, carbs: r.macros.carbs, fat: r.macros.fat,
  ingredients: r.ingredients || [], steps: r.steps || [], notes: r.notes || "",
})));

const json = (v) => JSON.stringify(v, null, 2);
const out = `// GENERATED by scripts/import-macros-data.mjs from the Macros repo (lib/data/plans.ts, snacks.ts, recipes.ts).
// Do not edit by hand: change Macros' files, or the generator, and run it again.
// ${Object.keys(plans).length} plans, ${Object.keys(BOWL_VARIANTS).length} bowl builds, ${snacks.length} quick snacks, ${recipes.length} recipes. Macros per serving, exactly as Macros has them.

export type MealSlot = "breakfast" | "lunch" | "snack" | "dinner";
export type MealPlanId = ${Object.keys(plans).map((k) => JSON.stringify(k)).join(" | ")};
export type BowlId = ${Object.keys(BOWL_VARIANTS).map((k) => JSON.stringify(k)).join(" | ")};
export type PlanMeal = { name: string; kcal: number; protein: number; carbs: number; fat: number; time: string; desc: string; fixedPortion?: boolean };
export type MealPlan = { id: MealPlanId; name: string; badge: string; desc: string; targets: { kcal: number; protein: number; carbs: number; fat: number }; meals: Record<MealSlot, PlanMeal>; extras: PlanMeal[] };
export type BowlVariant = { short: string; name: string; desc: string; kcal: number; protein: number; carbs: number; fat: number };
export type SnackPreset = { name: string; portion: string; kcal: number; protein: number; carbs: number; fat: number };
export type Recipe = { id: string; group: string; name: string; time: string; servings: number; isMealPrep: boolean; fixedPortion?: boolean; kcal: number; protein: number; carbs: number; fat: number; ingredients: string[]; steps: string[]; notes: string };

export const MEAL_PLANS: Record<MealPlanId, MealPlan> = ${json(plans)};

/** Swappable builds for the Standard plan's two bowl slots (lunch and dinner). */
export const BOWL_VARIANTS: Record<BowlId, BowlVariant> = ${json(BOWL_VARIANTS)};

export const SNACK_PRESETS: SnackPreset[] = ${json(snacks)};

export const RECIPES: Recipe[] = ${json(recipes)};
`;
const target = path.join(import.meta.dirname, "..", "src", "lib", "food-data.ts");
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${Object.keys(plans).length} plans, ${snacks.length} snacks, ${recipes.length} recipes (${recipes.map((r) => r.group).filter((g, i, a) => a.indexOf(g) === i).join(", ")})`);
